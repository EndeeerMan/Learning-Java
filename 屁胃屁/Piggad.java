class Piggad{
    private String name;
    private String gender;
    private boolean win;
    public void setName(String name){
        this.name = name;
    }
    public void setGender(String gender){
        this.gender = gender;
    }
    public void setWin(boolean win){
        this.win = win;
    }
    public String getName(){
        return name;
    }
    public String getGender(){
        return gender;
    }
    public boolean getWin(){
        return win;
    }
}